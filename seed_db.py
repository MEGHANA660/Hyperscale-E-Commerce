def _load_products():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "products.json")
    with open(path, encoding="utf-8") as fh:
        items = json.load(fh)
    return [
        {
            "id": p["id"],
            "name": p["name"],
            "description": p.get("description"),
            "price": float(p["price"]),
            "stock": int(p["stock"]),
            "category": p["category"],
            "image_url": p.get("image"),  # None -> the frontend draws a tile with the product name
            "rating": float(p.get("rating", 4.3)),
        }
        for p in items
    ]


